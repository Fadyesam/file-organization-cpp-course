// ============================================================
//  مثال 3: getline() مع char array
//  الهدف: توضيح ان الصيغة بتختلف شوية لو المتغير مش من نوع string
// ============================================================
#include <iostream>
using namespace std;

int main()
{
    char name[20];   // مصفوفة حروف بحجم 20 خانة كحد اقصى

    cout << "Enter Your Name: ";

    // هنا بتتكتب: cin.getline(...)  مش  getline(cin, ...)
    // الرقم 20 معناه: اقرأ لحد 19 حرف كحد اقصى + حرف النهاية '\0'
    cin.getline(name, 20);

    cout << "Hello, " << name << endl;

    return 0;
}

/*
   ملاحظة للطالب:
   - لو الاسم المدخل اطول من 19 حرف، هياخد اول 19 حرف بس ويقطع الباقي.
   - الفرق بين المثال ده والمثال الاول:
        string  ->  getline(cin, name);
        char[]  ->  cin.getline(name, size);
*/
